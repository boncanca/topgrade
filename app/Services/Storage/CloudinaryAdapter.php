<?php

namespace App\Services\Storage;

use CodebarAg\FlysystemCloudinary\FlysystemCloudinaryAdapter;
use League\Flysystem\Config;

class CloudinaryAdapter extends FlysystemCloudinaryAdapter
{
    /**
     * Image extensions mapped to the delivery format Cloudinary stores them under.
     *
     * @var array<string, string>
     */
    private const IMAGE_FORMATS = [
        'jpg' => 'jpg',
        'jpeg' => 'jpg',
        'png' => 'png',
        'webp' => 'webp',
        'gif' => 'gif',
        'avif' => 'avif',
    ];

    /**
     * Resolve delivery URL from Cloudinary.
     *
     * Files are uploaded with their extension kept as part of the public_id
     * (e.g. "folder/photo.png"), and Cloudinary serves them at "{public_id}.{format}"
     * (e.g. "folder/photo.png.png"). Cloudinary also normalizes "jpeg" to "jpg", so
     * "photo.jpeg" is served at "photo.jpeg.jpg". Without appending the format, the
     * plain URL returns HTTP 404 (verified live against the Cloudinary account).
     */
    public function getUrl(string|array $path): string|false
    {
        $rawPath = is_array($path) ? (string) ($path['path'] ?? '') : (string) $path;
        $url = parent::getUrl($path);

        if (! is_string($url)) {
            return false;
        }

        $extension = strtolower(pathinfo($rawPath, PATHINFO_EXTENSION));
        $format = self::IMAGE_FORMATS[$extension] ?? null;

        if ($format === null) {
            return $url;
        }

        $alreadyFormatted = preg_match('/\.'.preg_quote($extension, '/').'\.'.$format.'(?=[?#]|$)/i', $url) === 1;

        if ($alreadyFormatted) {
            return $url;
        }

        return preg_replace(
            '/(\.'.preg_quote($extension, '/').')(?=[?#]|$)/i',
            '$1.'.$format,
            $url
        ) ?? $url;
    }

    /**
     * Upload a stream to Cloudinary.
     *
     * The Cloudinary PHP SDK fails with BadRequest ("Unsupported source URL") when given
     * non-filesystem streams (e.g. php://memory or php://temp generated by Spatie Media Library).
     * Buffering in-memory streams into string contents delegates to write(), which safely writes
     * the buffer to a temporary file via CloudinaryStringUploadSource.
     */
    public function writeStream(string $path, $resource, Config $config): void
    {
        $meta = is_resource($resource) ? stream_get_meta_data($resource) : [];
        $uri = $meta['uri'] ?? null;

        if (is_string($uri) && file_exists($uri) && ! str_starts_with($uri, 'php://')) {
            parent::writeStream($path, $resource, $config);

            return;
        }

        $contents = stream_get_contents($resource);
        if ($contents !== false) {
            $this->write($path, $contents, $config);

            return;
        }

        parent::writeStream($path, $resource, $config);
    }

    /**
     * Delete a directory from Cloudinary.
     *
     * The vendor adapter's default implementation performs 4 separate Admin API calls
     * (listing raw, image, video assets and subfolders), then individually destroys each asset,
     * and finally deletes the folder. For Spatie Media Library (which creates a directory per media item),
     * this took ~36 seconds per media delete and quickly exhausted Cloudinary Admin API rate limits.
     *
     * Using deleteAssetsByPrefix() flushes all resources under the prefix in a single call (~1.5s).
     */
    public function deleteDirectory(string $path): void
    {
        $logicalDir = trim($path, '/');
        $prefixedDir = $this->pathsForMetadata()->prefixed($logicalDir);

        try {
            $this->cloudinary->adminApi()->deleteAssetsByPrefix($prefixedDir);
        } catch (\Throwable) {
            parent::deleteDirectory($path);

            return;
        }

        try {
            $this->cloudinary->adminApi()->deleteFolder($prefixedDir);
        } catch (\Throwable) {
            // Folders are virtual in Cloudinary unless explicitly created; safe to ignore.
        }
    }
}
